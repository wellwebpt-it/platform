const iso = parseLisbonDateTime('11/11/2026', '14:30');
assert.equal(formatLisbonDateInput(iso), '11/11/2026');
assert.equal(formatLisbonTimeInput(iso), '14:30');
assert.equal(toLisbonLocalDateTime(iso), '2026-11-11T14:30');
assert.throws(() => parseLisbonDateTime('31/02/2026', '12:00'), /não é válida/);
assert.throws(() => parseLisbonDateTime('01/01/2026', '24:00'), /não é válida/);
assert.throws(() => parseLisbonDateTime('29/03/2026', '01:30'), /não existe/);
assert.equal(normalizeWebsiteUrl('hotel.pt'), 'https://hotel.pt');
assert.equal(normalizeWebsiteUrl('www.hotel.pt'), 'https://www.hotel.pt');
assert.equal(normalizeWebsiteUrl('https://hotel.pt'), 'https://hotel.pt');
assert.equal(normalizeWebsiteUrl('http://hotel.pt'), 'http://hotel.pt');
assert.throws(() => normalizeWebsiteUrl('javascript:alert(1)'), /HTTP ou HTTPS/);
assert.throws(() => normalizeWebsiteUrl('data:text/html,hello'), /HTTP ou HTTPS/);
assert.throws(() => normalizeWebsiteUrl('https:// hotel.pt'), /válido/);

const oldService = {id:'s1',name:'Yoga',description:'Aula suave',modality_slug:'yoga',duration_minutes:60,price:30,currency:'EUR',active:true,has_material:false,allows_group:true,max_students:8,price_per_student:false};
const proposedService = {...oldService,name:'Yoga restaurativo',description:'Descrição completa da aula restaurativa',price:12,has_material:true,price_per_student:true};
const compared = compareServiceReview(proposedService,oldService,new Map([['yoga','Yoga'],['restorative','Yoga restaurativo']]));
