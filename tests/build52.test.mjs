assert.equal(compared.find(field=>field.key==='currency').value,'EUR');
assert.equal(compared.find(field=>field.key==='max_students').value,'8 alunos');
assert.equal(compared.find(field=>field.key==='price_per_student').value,'Por aluno');
const newService = compareServiceReview({...proposedService,id:'s2'});
assert.ok(newService.every(field=>field.changed));

